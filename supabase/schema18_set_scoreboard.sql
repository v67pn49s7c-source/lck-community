-- ══════════════════════════════════════════════════════════════════
-- schema18: 세트별 스코어보드 데이터 칸 만들기
-- ══════════════════════════════════════════════════════════════════
-- 왜:
--   지금 경기 상세는 선수 5명씩의 KDA 표뿐이라 밋밋하다. 리그피디아에는
--   밴/픽 순서·타워·억제기·드래곤·바론·전령·팀 골드·경기 시간이 다 있는데
--   받아 둘 자리가 없어서 못 쓰고 있었다.
--
-- 무엇을 하나:
--   match_details 에 game 이라는 칸 하나를 더한다. 세트 하나의 '경기 전체 기록'을
--   여기에 통째로 담는다(JSON). 칸을 열 몇 개로 쪼개지 않는 이유는, 앞으로
--   담을 것이 늘어나도(장로용·공허충 등) 표 구조를 다시 안 바꿔도 되기 때문이다.
--
--   담기는 모양 (예시):
--     {
--       "len": "25:09",                      경기 시간
--       "gold": {"a": 53200, "b": 38800},    팀 골드
--       "kills": {"a": 12, "b": 2},          팀 킬
--       "towers": {"a": 9, "b": 0},
--       "inhib": {"a": 3, "b": 0},
--       "dragons": {"a": 1, "b": 0},
--       "barons": {"a": 1, "b": 0},
--       "heralds": {"a": 1, "b": 0},
--       "bans": {"a": ["Camille","Orianna",…], "b": […]},   밴 순서 그대로
--       "picks": {"a": ["Jayce","Sejuani",…], "b": […]},    픽 순서 그대로
--       "blue": "a"                          어느 쪽이 블루 진영이었나
--     }
--   a/b 는 언제나 **우리 matches 표의 a팀/b팀** 기준이다 (블루/레드가 아니다).
--
-- 안전성:
--   칸을 더하기만 한다. 기존 데이터는 하나도 건드리지 않는다.
--   값이 없는(아직 재수집 안 한) 세트는 game 이 비어 있고, 화면은 그런 세트에서
--   스코어보드를 그냥 감춘다. 그래서 이 SQL 만 돌리고 재수집을 안 해도 아무 문제 없다.
--
-- 실행: Supabase → SQL Editor 에 통째로 붙여넣고 Run.
--       맨 아래가 '스코어보드 칸 OK' 면 성공.
-- ══════════════════════════════════════════════════════════════════

alter table match_details
  add column if not exists game jsonb not null default '{}'::jsonb;

-- 확인
select case
         when exists (
           select 1 from information_schema.columns
           where table_name = 'match_details' and column_name = 'game')
         then '스코어보드 칸 OK'
         else '실패 — game 칸이 만들어지지 않았습니다'
       end as "결과";
