-- ══════════════════════════════════════════════════════════════════
-- schema21: 대회별 대진 설정 칸
-- ══════════════════════════════════════════════════════════════════
--
-- 왜 필요한가:
--   대진표의 **모양**(열·행·자리 이름)은 코드에 적어 두면 된다 — LCK 형식은 잘 안 바뀐다.
--   그런데 두 가지는 대회마다 달라서 코드에 적을 수가 없다.
--
--   ① 시드 표 — "1시드가 어느 팀인가". 정규 라운드가 끝나야 정해진다.
--   ② 상자 ↔ 경기 연결 — 대진표의 어느 칸이 어느 경기인가.
--      리그피디아가 플레이오프 경기에 무슨 id 를 붙일지 **미리 알 수 없다.**
--      (Road to MSI 는 _Round1_1 이었지만 플레이오프도 그럴 거라는 보장이 없다)
--
--   지금은 경기 id 를 정규식으로 짐작하는데, 짐작이 틀리면 대진표가 빈 채로 남고
--   사장님이 고칠 방법이 없다. 이 칸이 그 탈출구다 — 관리자 화면에서 드롭다운으로 잇는다.
--
-- 담기는 모양 (예):
--   {
--     "seeds": ["gen","hle","t1","kt","dk",""],          시드 1~6 (빈 칸 = 아직 미정)
--     "links": { "UB-R1-M1": "경기id", "LB-R1": "경기id" }
--   }
--
-- 안전성:
--   칸을 더하기만 한다. 비어 있으면({}) 지금과 똑같이 동작한다.
--   권한도 손댈 필요 없다 — tournaments 의 관리자 쓰기 정책이 행 전체에 걸려 있어
--   새 칸도 자동으로 보호된다.
--
-- 실행: Supabase → SQL Editor 에 붙여넣고 Run.
-- ══════════════════════════════════════════════════════════════════

alter table tournaments
  add column if not exists bracket jsonb not null default '{}'::jsonb;

select case
    when exists (select 1 from information_schema.columns
                  where table_schema = 'public' and table_name = 'tournaments'
                    and column_name = 'bracket')
    then '대진 설정 칸 OK'
    else '실패 — 위 문장이 돌았는지 확인해 주세요'
  end as "결과";
