-- ── 후보(서브) 선수 표시 칸 ──────────────────────────────────────
--
-- 왜 필요한가 (사장님 2026-08-16):
--   홈 히어로에 DNS 정글러로 **표식**이 나오는데, 표식은 서브로 내려갔고
--   지금 주전은 **샤벨**이다. 그런데 우리 선수 표에는 주전·후보 구분이 없다.
--   한 포지션에 세 명(표식·샤벨·DDoiV)이 있으면 화면은 그냥 **먼저 등록된 사람**을
--   집는다. 그래서 로스터가 바뀌어도 옛 주전이 계속 나온다.
--
-- 왜 이 방법인가:
--   "최근에 실제로 출전한 선수"로 자동 판정하는 게 이상적이지만, 그 기록
--   (match_details)은 홈 화면에서 받지 않는다 — 가장 크고 느린 요청이라
--   경기 페이지에서만 받도록 예전에 떼어 놨다. 그걸 홈에서 다시 받으면
--   첫 화면이 느려진다. 그래서 표에 칸 하나를 두고 운영자가 정한다.
--
-- 안전성: 칸을 더하기만 한다. 비어 있으면(false) 지금과 똑같이 동작한다.

alter table players
  add column if not exists sub boolean not null default false;

-- 표식은 서브 정글러로 내려갔다 (샤벨이 주전)
update players set sub = true
 where id = 'dns-pyosik-1785696707312' and sub = false;

-- ── 확인 — DNS 정글러 셋 중 표식만 후보여야 한다 ──────────────────
select nick, pos, sub from players
 where team = 'dns' and pos = '정글' order by sub, nick;
