-- ============================================================
-- fix6: DB에 업로드해 둔 옛 로고 지우기 (새 로고 파일이 보이게)
-- ============================================================
-- 무엇이 문제였나:
--   관리자 화면에서 업로드한 로고는 site_settings 에 이미지 통째로
--   (data URL, 약 60KB) 저장되고, 저장돼 있으면 파일보다 **우선** 쓰인다.
--   그래서 새 로고 파일을 넣어도 화면에는 옛 로고가 계속 나온다.
--   덤으로 이 60KB 를 방문자가 하루 한 번씩 내려받는다.
--
-- 무엇을 하나:
--   업로드본을 지운다 → 저장소의 새 로고 파일(assets/brand/*.png)이 쓰인다.
--   ⚠ 되돌리려면 관리자 화면에서 다시 업로드하면 된다 (원본은 사장님 PC 에).
--
-- 실행: Supabase SQL Editor 에 전체 붙여넣기 → Run
--       실행 후 사이트에서 새로고침 한 번 (브라우저에 하루치 캐시가 남아 있음)
-- ============================================================

-- 지우기 전 확인 (몇 개가 대상인지)
select key, length(value) as "크기(문자)"
from site_settings where key like 'logo_%';

delete from site_settings where key like 'logo_%';

-- ── 확인 ─────────────────────────────────────────────────────
select case when count(*) = 0
  then '업로드 로고 정리 OK — 이제 새 로고 파일이 표시됩니다'
  else '⚠ ' || count(*) || '개가 남아 있음' end as "결과"
from site_settings where key like 'logo_%';
