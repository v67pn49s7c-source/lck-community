-- ── 잘못 저장된 세트 승자 1건 바로잡기 ────────────────────────────
--
-- 어떤 경기인가:
--   2026-08-01 젠지 0 : 2 디플러스 기아 (라운드 3-4 레전드 그룹)
--   최종 스코어가 0:2 이므로 두 세트 모두 DK(=b) 가 이긴 경기다.
--   그런데 1세트(set_index 0) 승자가 GEN(=a) 으로 저장돼 있었다.
--
-- 어떻게 확신하나 — 그 세트의 기록 자체가 DK 압승을 말한다:
--   킬 13:19 · 골드 60,200:71,400 · 타워 2:8   (전부 DK 우세)
--   여기에 최종 스코어 0:2 를 더하면 GEN 이 이긴 세트는 존재할 수 없다.
--
-- 왜 눈에 안 띄었나:
--   화면은 이런 어긋남을 발견하면 승패 배지를 "기록 확인 중"으로 바꿔 **숨긴다**.
--   틀린 승패를 당당히 보여 주는 것보다 낫지만, 그래서 조용히 남아 있었다.
--   (2026-08-16 국제 대회 기록을 넣다가 전 경기를 훑어서 찾았다)
--
-- ⚠ 다른 경기는 건드리지 않는다. 조건에 경기 id 와 현재 값을 함께 걸어,
--    이미 고쳐진 뒤에 다시 실행해도 아무 일도 일어나지 않게 한다.

update match_details
   set win = 'b'
 where match_id = 'lpLCK2026SeasonRounds3-4_Week10_8'
   and set_index = 0
   and win = 'a';

-- ── 확인 — 두 세트 모두 'b' 여야 한다 ─────────────────────────────
select set_index, win
  from match_details
 where match_id = 'lpLCK2026SeasonRounds3-4_Week10_8'
 order by set_index;
